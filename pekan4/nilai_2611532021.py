# Buat file dengan nama nilai_nim.py
# Buat program untuk nested if
# Nama variabel ditambah 4 digit nim terakhir contoh ipk_1234
# Program ini menggunakan fungsi input()
# Program konversi nilai angka ke huruf

nilai_2021 = int(input("Inputkan Nilai Angka= "))

if nilai_2021 >= 81:
    print("A")
elif nilai_2021 >= 70:
    print("B")
elif nilai_2021 >= 60:
    print("C")
elif nilai_2021 >= 50:
    print ("D")
else:
    print("E")